test('Link Capture route and URL-only saving work offline after first visit', async ({ browser }) => {
  const context = await browser.newContext()
  const page = await context.newPage()
  await page.goto(new URL('/flow/links', process.env.E2E_BASE_URL || 'http://127.0.0.1:3000').toString())
  await expect(page.getByRole('heading', { name: 'Save the useful parts.' })).toBeVisible()
  await page.waitForFunction(() => 'serviceWorker' in navigator && Boolean(navigator.serviceWorker.controller))
  await page.waitForFunction(async () => {
    const cache = await caches.open('notely-v4-local-first')
    return Boolean(await cache.match('/flow/links'))
  })
  await page.getByLabel('Webpage URL').fill('https://example.com/offline-article')
  await context.setOffline(true)
  await expect(page.getByRole('button', { name: 'Reading requires internet' })).toBeDisabled()
  await page.getByRole('button', { name: 'Save URL on this device' }).click()
  await expect(page.getByText('URL saved to your Notely notes.')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Save the useful parts.' })).toBeVisible()
  await context.close()
})


test('pasted images render inline and survive a guest offline reload', async ({ browser }) => {
  const context = await browser.newContext()
  const page = await context.newPage()
  await page.goto(process.env.E2E_BASE_URL || 'http://127.0.0.1:3000')
  const privateImageResponse = await page.request.get('/api/note-images?path=00000000-0000-4000-8000-000000000000/00000000-0000-4000-8000-000000000000/image.png')
  expect(privateImageResponse.status()).toBe(401)
  await page.getByRole('button', { name: 'New note' }).click()
  await page.locator('.desktop-editor textarea.note-title').fill('Image paste test')
  const editor = page.locator('.desktop-editor [contenteditable="true"]')
  await editor.fill('Text before the image')
  await editor.evaluate(element => {
    element.focus()
    const range = document.createRange()
    range.selectNodeContents(element)
    range.collapse(false)
    const selection = window.getSelection()
    selection?.removeAllRanges()
    selection?.addRange(range)
    const encoded = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/K3sAAAAASUVORK5CYII='
    const bytes = Uint8Array.from(atob(encoded), character => character.charCodeAt(0))
    const file = new File([bytes], 'clipboard.png', { type: 'image/png' })
    const transfer = new DataTransfer()
    transfer.items.add(file)
    element.dispatchEvent(new ClipboardEvent('paste', { bubbles: true, cancelable: true, clipboardData: transfer }))
  })
  await expect(editor.locator('img.note-inline-image')).toHaveCount(1)
  await expect(editor).toContainText('Text before the image')
  await editor.evaluate(element => {
    const encoded = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/K3sAAAAASUVORK5CYII='
    const bytes = Uint8Array.from(atob(encoded), character => character.charCodeAt(0))
    const transfer = new DataTransfer()
    transfer.items.add(new File([bytes], 'dropped.png', { type: 'image/png' }))
    element.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: transfer }))
  })
  await expect(editor.locator('img.note-inline-image')).toHaveCount(2)
  await page.waitForTimeout(500)
  await page.reload()
  await page.locator('.note-item').filter({ hasText: 'Image paste test' }).click()
  const reopenedEditor = page.locator('.desktop-editor [contenteditable="true"]')
  await expect(reopenedEditor.locator('img.note-inline-image')).toHaveCount(1)
  await expect(reopenedEditor).toContainText('Text before the image')
  await context.setOffline(true)
  await page.reload()
  await page.locator('.note-item').filter({ hasText: 'Image paste test' }).click()
  await expect(page.locator('.desktop-editor [contenteditable="true"] img.note-inline-image')).toHaveCount(1)
  await context.close()
})
